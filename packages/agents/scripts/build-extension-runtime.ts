/**
 * Bundle the extension runtime (src/harness/think/extensions/worker-entry.ts)
 * into one ES module and embed it as a string, so a loader can run an
 * extension from source in a dynamic Worker with the same runtime that runs
 * bundled extensions in process.
 *
 * Writes src/harness/think/extensions/worker-runtime.generated.ts (not
 * committed). Run by scripts/build.ts before the package build.
 */
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { build } from "esbuild";

const OUT = "src/harness/think/extensions/worker-runtime.generated.ts";

export async function buildExtensionRuntime(): Promise<void> {
  const result = await build({
    entryPoints: ["src/harness/think/extensions/worker-entry.ts"],
    bundle: true,
    platform: "neutral",
    format: "esm",
    target: "es2022",
    minify: true,
    write: false,
    legalComments: "none",
    external: ["cloudflare:workers", "./extension.js", "./manifest.js"]
  });
  const source = result.outputFiles[0]?.text;
  if (!source) throw new Error("The extension runtime bundle is empty");
  const version = createHash("sha256")
    .update(source)
    .digest("hex")
    .slice(0, 16);
  writeFileSync(
    OUT,
    [
      "// Generated by scripts/build-extension-runtime.ts. Do not edit.",
      "",
      "/** The extension runtime, bundled: a dynamic Worker's main module. */",
      `export const EXTENSION_WORKER_RUNTIME: string = ${JSON.stringify(source)};`,
      "",
      "/** A hash of `EXTENSION_WORKER_RUNTIME`, to tell runtime builds apart. */",
      `export const EXTENSION_WORKER_RUNTIME_VERSION = ${JSON.stringify(version)};`,
      ""
    ].join("\n")
  );
  console.log(
    `extension runtime: ${(source.length / 1024).toFixed(1)} KiB, ${version}`
  );
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await buildExtensionRuntime();
}
